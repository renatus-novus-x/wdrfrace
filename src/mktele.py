def draw_line(rows, x0, y0, x1, y1):
    dx = abs(x1 - x0)
    sx = 1 if x0 < x1 else -1
    dy = -abs(y1 - y0)
    sy = 1 if y0 < y1 else -1
    error = dx + dy
    while True:
        rows[y0] |= 1 << (WIDTH - 1 - x0)
        if x0 == x1 and y0 == y1:
            return
        twice = error * 2
        if twice >= dy:
            error += dy
            x0 += sx
        if twice <= dx:
            error += dx
            y0 += sy


def rasterize(character):
    rows = [0] * HEIGHT
    for stroke in GLYPHS[character]:
        for start, end in zip(stroke, stroke[1:]):
            draw_line(rows, start[0], start[1], end[0], end[1])
    return rows


def emit_table(name, characters):
    print("static const uint8_t %s[%d][%d] = {" % (name, len(characters), HEIGHT))
    for character in characters:
        rows = rasterize(character)
        print("  {%s},  /* %s */" % (", ".join(str(row) for row in rows), character))
    print("};\n")


